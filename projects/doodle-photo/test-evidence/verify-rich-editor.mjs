import {createRequire} from 'node:module'
import {readFile,writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
import assert from 'node:assert/strict'
const require=createRequire('C:/Users/xiaojiang/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json')
const {chromium}=require('playwright')
const browser=await chromium.launch({headless:true,channel:'msedge'})
const base=new URL('./',import.meta.url)
try{
 const analysis=JSON.parse(await readFile(new URL('custom-sketch-coffee-live.json',base),'utf8'))
 const custom=analysis.decorations.find(d=>d.type==='custom')
 assert.ok(custom,'real API should provide a photo-related custom sketch for this test')
 const page=await browser.newPage({viewport:{width:1200,height:1200}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/api/analyze',route=>route.fulfill({contentType:'application/json',body:JSON.stringify(analysis)}))
 await page.goto('http://127.0.0.1:8879/')
 await page.locator('input[type=file]').setInputFiles(fileURLToPath(new URL('coffee.jpg',base)))
 await page.waitForFunction(()=>!document.querySelector('button.bg-purple-500')?.disabled)
 await page.getByRole('button',{name:`移动${custom.label}`,exact:true}).waitFor()
 const afterPaint=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
 await page.getByRole('button',{name:`移动${custom.label}`,exact:true}).click()
 await page.getByRole('button',{name:'放大',exact:true}).click()
 await page.getByRole('button',{name:'旋转',exact:true}).click()
 const count=await page.getByRole('button',{name:/^移动/}).count()
 await page.getByRole('button',{name:'删除',exact:true}).click()
 assert.equal(await page.getByRole('button',{name:/^移动/}).count(),count-1)
 await page.getByRole('button',{name:'撤销',exact:true}).click()
 await page.getByRole('button',{name:`移动${custom.label}`,exact:true}).waitFor()
 await page.getByLabel('手绘元素',{exact:true}).selectOption('camera')
 await page.getByRole('button',{name:'添加手绘元素',exact:true}).click()
 assert.equal(await page.getByRole('button',{name:/^移动/}).count(),count+1)
 const camera=page.getByRole('button',{name:'移动相机',exact:true}).last()
 for(let i=0;i<9;i++)await page.getByRole('button',{name:'旋转',exact:true}).click()
 await page.getByRole('button',{name:'放大',exact:true}).click()
 const canvasBox=await page.locator('canvas').boundingBox(),box=await camera.boundingBox()
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
 await page.mouse.down();await page.mouse.move(canvasBox.x+canvasBox.width+60,canvasBox.y+15,{steps:8});await page.mouse.up()
 const moved=await camera.boundingBox()
 assert.ok(moved.x>=canvasBox.x && moved.y>=canvasBox.y)
 assert.ok(moved.x+moved.width<=canvasBox.x+canvasBox.width+.5 && moved.y+moved.height<=canvasBox.y+canvasBox.height+.5)
 await afterPaint()
 const preview=await page.locator('canvas').evaluate(c=>c.toDataURL().split(',')[1])
 await page.getByRole('button',{name:'生成图片',exact:true}).click()
 const pending=page.waitForEvent('download');await page.getByRole('button',{name:'导出图片',exact:true}).click()
 const download=await pending,output=new URL('custom-sketch-edited.png',base)
 await download.saveAs(fileURLToPath(output))
 assert.deepEqual(await readFile(output),Buffer.from(preview,'base64'))
 assert.deepEqual(errors,[])
 const result={customLabel:custom.label,customEditing:true,deleteAndUndo:true,manualCamera:true,rotatedDragWithinBounds:true,previewMatchesExport:true}
 await writeFile(new URL('rich-editor-verification.json',base),JSON.stringify(result,null,2))
 console.log(JSON.stringify(result))
}finally{await browser.close()}
